// Builds worker/esimairports.data.mjs from the OurAirports public-domain CSVs.
// Source: https://davidmegginson.github.io/ourairports-data/ (Public Domain).
//
//   node scripts/build-esim-airports.mjs data/airports.csv data/countries.csv
//
// Keeps only airports a traveller actually lands at: scheduled passenger
// service, a three-letter IATA code, and a real airport or seaplane base.
// Heliports are dropped. Output is deterministic (sorted by IATA) so a
// rebuild with unchanged data produces an unchanged file.

import { readFileSync, writeFileSync } from 'node:fs';

export function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else { quoted = false; }
      } else {
        field += ch;
      }
      continue;
    }
    if (ch === '"') { quoted = true; continue; }
    if (ch === ',') { row.push(field); field = ''; continue; }
    if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.length > 1 || row[0] !== '') rows.push(row);
      row = [];
      continue;
    }
    field += ch;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  const [head, ...body] = rows;
  return body.map((r) => Object.fromEntries(head.map((h, j) => [h, r[j] ?? ''])));
}

const SIZE = { large_airport: 'L', medium_airport: 'M', small_airport: 'S', seaplane_base: 'W' };

export function buildAirports(airportRows) {
  const out = [];
  const seen = new Set();
  for (const r of airportRows) {
    const iata = (r.iata_code || '').trim().toUpperCase();
    if (r.scheduled_service !== 'yes') continue;
    if (!/^[A-Z]{3}$/.test(iata)) continue;
    const size = SIZE[r.type];
    if (!size) continue;
    const country = (r.iso_country || '').trim().toUpperCase();
    if (!/^[A-Z]{2}$/.test(country) || country === 'ZZ') continue;
    if (seen.has(iata)) continue;
    seen.add(iata);
    out.push([iata, r.name.trim(), (r.municipality || '').trim(), country, size]);
  }
  out.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  return out;
}

export function buildCountries(countryRows) {
  const names = {};
  const continents = {};
  for (const r of countryRows) {
    const code = (r.code || '').trim().toUpperCase();
    // ZZ is OurAirports' "unknown or unassigned" bucket, not a place anyone flies to.
    if (!/^[A-Z]{2}$/.test(code) || code === 'ZZ') continue;
    names[code] = r.name.trim();
    const cont = (r.continent || '').trim().toUpperCase();
    if (/^(AF|AN|AS|EU|NA|OC|SA)$/.test(cont)) continents[code] = cont;
  }
  const sort = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => (a < b ? -1 : 1)));
  return { names: sort(names), continents: sort(continents) };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [airportsCsv, countriesCsv, outFile = 'worker/esimairports.data.mjs'] = process.argv.slice(2);
  if (!airportsCsv || !countriesCsv) {
    console.error('usage: node scripts/build-esim-airports.mjs <airports.csv> <countries.csv> [out.mjs]');
    process.exit(2);
  }
  const airports = buildAirports(parseCsv(readFileSync(airportsCsv, 'utf8')));
  const { names: countries, continents } = buildCountries(parseCsv(readFileSync(countriesCsv, 'utf8')));
  const header =
    '// GENERATED by scripts/build-esim-airports.mjs from OurAirports (Public Domain).\n' +
    '// Do not edit by hand. Rows: [IATA, airport name, city, ISO country, size L/M/S/W].\n';
  const body =
    `export const COUNTRIES = ${JSON.stringify(countries)};\n` +
    `export const CONTINENTS = ${JSON.stringify(continents)};\n` +
    `export const AIRPORTS = ${JSON.stringify(airports)};\n`;
  writeFileSync(outFile, header + body);
  console.log(`airports: ${airports.length}  countries: ${Object.keys(countries).length}  -> ${outFile}`);
}
